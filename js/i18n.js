const typewriter_phrases = {
  vi: ["Thần Tượng Của Bạn", "Ba Mẹ Yêu Dấu", "Bé Cưng", "Boss Mèo", "Người Ấy"],
  en: ["Your Idol", "Beloved Parents", "Sweet Baby", "Cat Boss", "That Special Someone"]
};

// Expose variable so typewriter script can use it
window.currentPhrases = typewriter_phrases.vi;
window.isTypewriterReset = false;

function initLang() {
  let lang = localStorage.getItem("lang");
  if (!lang) {
    const browserLang = navigator.language || navigator.userLanguage;
    lang = browserLang.startsWith("vi") ? "vi" : "en";
  }
  setLanguage(lang);
}

function setLanguage(lang) {
  localStorage.setItem("lang", lang);
  document.documentElement.lang = lang;
  
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang] && translations[lang][key]) {
      // For elements with mixed SVG/text, we might need a more targeted approach.
      // But based on the template, we'll wrap the textual parts in spans with data-i18n
      el.innerHTML = translations[lang][key];
    }
  });

  // Update typewriter phrases
  window.currentPhrases = typewriter_phrases[lang] || typewriter_phrases.en;
  
  // Highlight active language button
  const viBtn = document.getElementById("lang-vi");
  const enBtn = document.getElementById("lang-en");
  
  if (viBtn && enBtn) {
    if (lang === "vi") {
      viBtn.classList.add("text-primary", "font-bold");
      viBtn.classList.remove("text-gray-400");
      enBtn.classList.remove("text-primary", "font-bold");
      enBtn.classList.add("text-gray-400");
    } else {
      enBtn.classList.add("text-primary", "font-bold");
      enBtn.classList.remove("text-gray-400");
      viBtn.classList.remove("text-primary", "font-bold");
      viBtn.classList.add("text-gray-400");
    }
  }
}

document.addEventListener("DOMContentLoaded", initLang);
